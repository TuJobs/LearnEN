type RawWord = Omit<Word, 'id' | 'topic'>

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')

const topic = (id: TopicId, list: RawWord[]): Word[] =>
  list.map((w) => ({ ...w, id: slug(w.word), topic: id }))

